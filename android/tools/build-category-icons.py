def paths(svg: str):
    out = []
    for d in re.findall(r'<path[^>]*?\sd="([^"]+)"', svg):
        if d == "M0 0h24v24H0z":
            continue
        out.append(d)
    if re.search(r"<(circle|rect|line|polyline|polygon|ellipse)\b", svg):
        raise SystemExit("non-path element")
    return out

def write_kotlin(out, version, groups):
    def quoted(value):
        return json.dumps(value, ensure_ascii=False).replace("$", "\\$")
    chunks = [f"// Generated from Tabler Icons {version} outline. MIT, copyright (c) Paweł Kuna. Do not edit.\n"
        "package com.yohaku.expensetracker.domain.category\n\n"
        f"const val CATEGORY_ICON_SOURCE = \"Tabler Icons {version}\"\n"
        "data class CategoryIcon(val id:String,val zh:String,val ja:String,val keywords:String,val paths:List<String>)\n"
        "data class CategoryIconGroup(val id:String,val zh:String,val ja:String,val icons:List<CategoryIcon>)\n\n"]
    for group in groups:
        rows = ["|".join([i["id"], i["zh"], i["ja"], i["kw"], *i["paths"]]) for i in group["icons"]]
        encoded = "\n".join(rows)
        assert len(encoded.encode("utf-8")) < 65535, group["id"]
        chunks.append(f"private const val DATA_{group['id'].upper()} = {quoted(encoded)}\n\n")
    chunks.append("private fun parseIcons(data:String)=data.lineSequence().map { line ->\n"
        "    val fields=line.split('|')\n"
        "    CategoryIcon(fields[0],fields[1],fields[2],fields[3],fields.drop(4))\n"
        "}.toList()\n\nval categoryIconGroups:List<CategoryIconGroup> by lazy { listOf(\n")
    chunks.append(",\n".join(f"    CategoryIconGroup({quoted(g['id'])},{quoted(g['zh'])},{quoted(g['ja'])},parseIcons(DATA_{g['id'].upper()}))" for g in groups))
    chunks.append("\n) }\nprivate val iconsById by lazy { categoryIconGroups.flatMap{it.icons}.associateBy{it.id} }\n"
        "private val groupsByIconId by lazy { categoryIconGroups.flatMap{g->g.icons.map{it.id to g}}.toMap() }\n"
        "fun categoryIconOf(id:String?):CategoryIcon?=iconsById[id]\n"
        "fun categoryIconGroupOf(iconId:String?):CategoryIconGroup?=groupsByIconId[iconId]\n")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("".join(chunks))

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("package", type=Path)
    parser.add_argument("js", type=Path)
    parser.add_argument("--kotlin", type=Path)
    args = parser.parse_args()
    pkg, out = args.package, args.js
    version = json.loads((pkg / "package.json").read_text())["version"]
    seen, groups = set(), []
    for gid, gzh, gja, items in GROUPS:
        icons = []
        for tid, zh, ja, kw in items:
            assert tid not in seen, tid
            seen.add(tid)
            svg = (pkg / "icons" / "outline" / f"{tid}.svg").read_text()
            icons.append({"id": tid, "zh": zh, "ja": ja, "kw": kw, "paths": paths(svg)})
        groups.append({"id": gid, "zh": gzh, "ja": gja, "icons": icons})
    out.write_text(
        f"/* Curated category icons from Tabler Icons {version} outline (MIT, (c) Paweł Kuna). Generated; do not edit. */\n"
        f"const CATEGORY_ICON_SOURCE='Tabler Icons {version}';\n"
        "const CATEGORY_ICON_GROUPS=" + json.dumps(groups, ensure_ascii=False, separators=(",", ":")) + ";\n")
    if args.kotlin:
        write_kotlin(args.kotlin, version, groups)
    print(version, len(seen), "icons", out.stat().st_size, "bytes")

main()
